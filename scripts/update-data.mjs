#!/usr/bin/env node
// Refreshes bundled third-party data. Run before a release:
//
//   node scripts/update-data.mjs
//
//   src/background/domains/psl-data.js  ← Mozilla's Public Suffix List
//     (MPL-2.0; https://publicsuffix.org). Converted to punycode, because
//     browsers hand extensions ASCII hostnames.

import { writeFileSync } from "node:fs";
import { domainToASCII } from "node:url";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PSL_URL = "https://publicsuffix.org/list/public_suffix_list.dat";

async function updatePsl() {
  const res = await fetch(PSL_URL, { headers: { "user-agent": "openroute-update-data" } });
  if (!res.ok) throw new Error(`PSL download failed: HTTP ${res.status}`);
  const text = await res.text();
  const rules = new Set();
  for (const raw of text.split("\n")) {
    const line = raw.trim().split(/\s/)[0];
    if (!line || line.startsWith("//")) continue;
    const prefix = line.startsWith("!") ? "!" : line.startsWith("*.") ? "*." : "";
    const ascii = domainToASCII(line.slice(prefix.length));
    if (!ascii) throw new Error(`could not punycode PSL rule "${line}"`);
    rules.add(prefix + ascii.toLowerCase());
  }
  const sorted = [...rules].sort();
  const sha = createHash("sha256").update(text).digest("hex").slice(0, 16);
  const body = `// Generated by scripts/update-data.mjs — do not edit.
// Public Suffix List (https://publicsuffix.org), converted to punycode.
// This Source Code Form is subject to the terms of the Mozilla Public
// License, v. 2.0. If a copy of the MPL was not distributed with this
// file, You can obtain one at https://mozilla.org/MPL/2.0/.
export const PSL_META = ${JSON.stringify({ fetched: new Date().toISOString().slice(0, 10), sha256: sha, rules: sorted.length })};
export default ${JSON.stringify(sorted.join("\n"))};
`;
  writeFileSync(join(ROOT, "src", "background", "domains", "psl-data.js"), body);
  console.log(`✓ PSL: ${sorted.length} rules (sha ${sha})`);
}

await updatePsl();
